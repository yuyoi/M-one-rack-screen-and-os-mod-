"""dsp/presets.py -> firmware/mone_dev/presets.h, the PRESET page's table.  py -3.10 tools/gen_presets.py

Each preset keeps its (address, value) writes except the key-dependent ones: TUNE's speed + snap map (X:$0B,
X:$23-$2E) and HARMONY's two maps (X:$0244-$025B). The ESP recomputes those for its TUNE page key / scale from the
preset's tune spec (speed, chromatic or key) and harmony voices (indexes into HARM_DEF in menu.h), then sends
everything in one halt.
"""
import os
import re
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'dsp'))
import presets as PR  # noqa: E402

FW = os.path.join(HERE, '..', 'firmware', 'mone_dev')
TYPES = ['STUDIO', 'TUNE', 'HARMONY', 'LO-FI / RADIO', 'MONSTER', 'AMBIENT']
SKIP = {0x0B} | set(range(0x23, 0x2F)) | set(range(0x0244, 0x025C))


def harm_def():
    src = open(os.path.join(FW, 'menu.h'), encoding='utf-8').read()
    body = re.search(r'HARM_DEF\[\d+\]\[2\] = \{(.*?)\};', src, re.S).group(1)
    return [(int(d), int(v)) for d, v in re.findall(r'\{\s*(-?\d+)\s*,\s*(-?\d+)\s*\}', body)]


def voice_index(v, table):
    """('dia', steps) / ('st', n) -> HARM_DEF index; a fixed +-12 is the same map as the diatonic octave"""
    if v is None:
        return -1
    d, n = (1 if v[0] == 'dia' else 0), v[1]
    for alt in ((d, n), (1, 7) if (d, n) == (0, 12) else None, (1, -7) if (d, n) == (0, -12) else None):
        if alt in table:
            return table.index(alt)
    raise SystemExit('preset voice %r has no HARM_DEF entry in menu.h' % (v,))


def c_str(s):
    return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


def main():
    table = harm_def()
    out = ['// Generated by tools/gen_presets.py from dsp/presets.py: do not edit.',
           '#pragma once', '',
           'static const char *const PRESET_TYPES[] = {%s};' % ', '.join(c_str(t) for t in TYPES),
           'static const int N_PTYPES = %d;' % len(TYPES), '',
           'struct PresetDef {',
           '  uint8_t n; const char *name; uint8_t type; const char *note;',
           '  uint8_t chainN; uint8_t chain[6]; uint8_t strip;  // strip: STRIP on (X:$0207 = 1)',
           '  int8_t tuneSpeed; uint8_t tuneChrom;  // speed -1 = no TUNE settings; chrom 1 = chromatic, 0 = the key',
           '  int8_t v1, v2;                        // HARMONY voices: HARM_DEF index, -1 = off',
           '  uint8_t nw; const uint16_t *wa; const uint32_t *wv;',
           '};', '']
    rows = []
    for p in PR.P:
        if p['type'] not in TYPES:
            raise SystemExit('unknown preset type %r' % p['type'])
        w = [(a, v) for a, v in PR.writes(p) if a not in SKIP]
        k = 'p%02d' % p['n']
        out.append('static const uint16_t %s_a[] = {%s};' % (k, ', '.join('0x%04X' % a for a, _ in w)))
        out.append('static const uint32_t %s_v[] = {%s};' % (k, ', '.join('0x%06X' % (v & 0xFFFFFF) for _, v in w)))
        t = p['tune']
        h = p['harmony'] if PR.HARMONY in p['chain'] else None
        chain = list(p['chain']) + [0] * (6 - len(p['chain']))
        rows.append('  {%d, %s, %d, %s, %d, {%s}, %d, %d, %d, %d, %d, %d, %s_a, %s_v},' % (
            p['n'], c_str(p['name']), TYPES.index(p['type']), c_str(p['note']), len(p['chain']),
            ', '.join(str(c) for c in chain), 1 if p['strip'] else 0, t['speed'] if t else -1,
            1 if t and t['scale'] == 'chromatic' else 0, voice_index(h['v1'], table) if h else -1,
            voice_index(h.get('v2'), table) if h else -1, len(w), k, k))
    out += ['', 'static const PresetDef PRESETS[] = {'] + rows + ['};',
                                                            'static const int N_PRESETS = %d;' % len(rows), '']
    path = os.path.join(FW, 'presets.h')
    tmp = path + '.tmp'
    open(tmp, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    os.replace(tmp, path)
    print('wrote %s: %d presets, %d writes' % (path, len(rows), sum(len(PR.writes(p)) for p in PR.P)))


if __name__ == '__main__':
    main()
