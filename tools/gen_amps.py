"""AMP voicings (dsp/model/amp_voicings.py) -> firmware/mone_dev/amps_dsp.h.  py -3.10 tools/gen_amps.py

Per voicing: name, colour, stage gains (dB, at GAIN 70; the ESP's ampFill keeps its 0.25 dB per GAIN step), the
tone-stack parts for ampTmb (C1 C2 C3 R1 R2 R3 R4; none for DI = flat words), the coupling-HPF / Miller-LPF words
(X:$12C6-$12CB, ready to write), the row defaults (BASS MID TREBLE PRESENCE RESONANCE DRIVE SAG MASTER), the board's
knobs (label -> AMP row) and the cab IR (512 words: write them to Y:$0800 AND to AMP's SRAM table X:$031C00, the
table's param block X:$031E60 gets the same words as X:$12C0, so AMP's first-call init loads the voicing too).
"""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'dsp', 'model'))
import numpy as np  # noqa: E402
import amp_voicings as V  # noqa: E402
import amp_ref as AR  # noqa: E402

FW = os.path.join(HERE, '..', 'firmware', 'mone_dev')
ROWS = ['TYPE', 'GAIN', 'BASS', 'MID', 'TREBLE', 'PRESENCE', 'RESONANCE', 'DRIVE', 'SAG', 'MASTER']


def w24(v):
    return int(round(float(v) * AR.Q)) & 0xFFFFFF


def emit():
    out = ['// Generated by tools/gen_amps.py from dsp/model/amp_voicings.py. Do not edit.',
           '// AMP (effect 6) voicings for the PEDAL board / AMP page. Rows = menu.h ampP indices.',
           '#pragma once', '#include <stdint.h>',
           'struct AmpVoicing { const char *name; uint32_t col; int8_t g[3]; bool flat; double parts[7];',
           '                    uint32_t hplp[6]; int16_t def[8]; const uint32_t *ir;',
           '                    uint8_t nk; const char *klabel[6]; uint8_t krow[6]; };',
           '// def: BASS MID TREBLE (0..100) PRESENCE RESONANCE DRIVE (dB) SAG MASTER (%); hplp -> X:$12C6..$12CB', '']
    irs, defs = {}, []
    for name, v in V.VOICINGS.items():
        if v['cab'] not in irs:
            c = 'amp_ir_' + ''.join(ch if ch.isalnum() else '_' for ch in v['cab'])
            irs[v['cab']] = c
            out.append('static const uint32_t %s[512] = {%s};' % (c, ', '.join('0x%06X' % w24(x) for x in V.cab_ir(v['cab']))))
        w = V.words(name)
        hplp = [w24(w[6 + i]) for i in range(6)]
        d = v['d']
        df = [d['bass'], d['mid'], d['treble'], d['presence'], d['resonance'], d['drive'], d['sag'], d['master']]
        parts = v['parts'] or (0,) * 7
        kn = V.KNOBS[name]
        defs.append('  {"%s", 0x%06X, {%d, %d, %d}, %s, {%s}, {%s}, {%s}, %s, %d, {%s}, {%s}},' % (
            name, v['colour'], *v['g'], 'true' if v['parts'] is None else 'false',
            ', '.join('%.4g' % p for p in parts), ', '.join('0x%06X' % x for x in hplp), ', '.join(str(x) for x in df),
            irs[v['cab']], len(kn), ', '.join('"%s"' % l for l, _ in kn), ', '.join(str(ROWS.index(r)) for _, r in kn)))
    out += ['', 'static const AmpVoicing AMP_VOICINGS[] = {'] + defs + ['};',
            'static const int AMP_NV = sizeof AMP_VOICINGS / sizeof AMP_VOICINGS[0];', '']
    path = os.path.join(FW, 'amps_dsp.h')
    tmp = path + '.tmp'
    open(tmp, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    os.replace(tmp, path)
    print('wrote', path, '(%d voicings, %d IRs)' % (len(defs), len(irs)))


if __name__ == '__main__':
    emit()
