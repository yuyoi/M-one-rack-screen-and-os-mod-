"""The PEDAL board's DSP pedals -> firmware/mone_dev/pedals_dsp.h (the ESP's tables).  py -3.10 tools/gen_pedals.py

A pedal is just writes (no math on the ESP):
  pick a pedal  : its param block (init words, at the default knobs), every knob's words at the knob's position,
                  its curves (257 words each) and the kernel's FX id, all in one halt;
  move a knob   : that knob's table words (1-8 X writes).
Every param word belongs to one knob table (checked here); the two knob pairs that share one filter (Metal Zone
MIDDLE x MIDFREQ, Metal Muff TOP x BOOST) get one 2-D table, 21 x 21 (or 21 x 2 for a switch).
1-D knobs have 101 steps (position 0..100), 2-D tables 21 steps per knob (position / 5).
"""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'dsp', 'model'))
import numpy as np  # noqa: E402
import dirt_model as dm  # noqa: E402
import dirt_ref as R  # noqa: E402

FW = os.path.join(HERE, '..', 'firmware', 'mone_dev')
FX_DIRT = 17                                   # proposed id (VOCAL_ARCH.md, FX lab)
STEPS1, STEPS2 = 101, 21


def words_at(name, kn):
    return R.ints(R.build(name, kn)[0])


def knob_tables(name):
    """-> list of tables: dict(knobs=[i] or [i, j], steps=[..], addr=[X..], val=[[word..] per step (row-major)])"""
    p = dm.PEDALS[name]
    labels = [k[0] for k in p['knobs']]
    d = dm.knobs_default(name)
    base = words_at(name, d)
    deps = []
    for lab in labels:
        ch = set()
        for x in np.linspace(0, 1, 11):
            wv = words_at(name, {**d, lab: x})
            ch |= {i for i in range(R.NPAR) if wv[i] != base[i]}
        deps.append(ch)
    tabs, done = [], set()
    for i, lab in enumerate(labels):
        if i in done or not deps[i]:
            continue
        pair = [j for j in range(len(labels)) if j != i and deps[i] & deps[j]]
        assert len(pair) <= 1, (name, lab, 'shares words with more than one knob')
        if pair:
            j = pair[0]
            idx = sorted(deps[i] | deps[j])
            sw = [2 if p['knobs'][k][1] == 'S' else STEPS2 for k in (i, j)]
            val = []
            for a in range(sw[0]):
                for b in range(sw[1]):
                    wv = words_at(name, {**d, lab: a / (sw[0] - 1), labels[j]: b / (sw[1] - 1)})
                    val.append([wv[k] for k in idx])
            tabs.append(dict(knobs=[i, j], steps=sw, addr=[R.PAR + k for k in idx], val=val))
            done |= {i, j}
        else:
            idx = sorted(deps[i])
            st = 2 if p['knobs'][i][1] == 'S' else STEPS1
            val = [[words_at(name, {**d, lab: s / (st - 1)})[k] for k in idx] for s in range(st)]
            tabs.append(dict(knobs=[i], steps=[st], addr=[R.PAR + k for k in idx], val=val))
            done.add(i)
    return tabs


def cid(name):
    return ''.join(c if c.isalnum() else '_' for c in name).strip('_').lower()


def emit(names):
    out = ['// Generated by tools/gen_pedals.py from dsp/model/dirt_model.py + dirt_ref.py. Do not edit.',
           '// A pedal = writes. Pick: X words init[] at par.., every table at its knobs\' positions, the curves, then',
           '// FX id. Knob move: its table(s). 1-D: val[step * nw + w], step = pos (0..100). 2-D: val[(s0 * steps1 + s1)',
           '// * nw + w], s = pos / 5 (21 steps) or 0/1 for a switch (pos >= 50). Words are 24-bit, long X writes.',
           '#pragma once',
           '#include <stdint.h>',
           'struct PdTab { uint8_t nk; uint8_t k[2]; uint8_t steps[2]; uint8_t nw; const uint16_t *addr; const uint32_t *val; };',
           'struct PdCurve { uint16_t addr; const uint32_t *val; };            // 257 words',
           'struct PdKnob { const char *label; uint8_t def; };                  // def = 0..100',
           'struct PdDef { const char *name; uint32_t col; uint8_t fx; uint16_t par; uint8_t npar; const uint32_t *init;',
           '               uint8_t ncurve; const PdCurve *curve; uint8_t nk; const PdKnob *k; uint8_t ntab; const PdTab *tab; };',
           '']
    defs = []
    total = 0
    for name in names:
        c = cid(name)
        p = dm.PEDALS[name]
        d = dm.knobs_default(name)
        w, curves, _ = R.build(name, d)
        init = R.ints(w)
        out.append('// ---- %s' % name)
        out.append('static const uint32_t pd_%s_init[%d] = {%s};' % (c, R.NPAR, ', '.join('0x%06X' % v for v in init)))
        cl = []
        for k, (addr, t) in enumerate(sorted(curves.items())):
            tv = R.tab_ints(t)
            out.append('static const uint32_t pd_%s_c%d[257] = {%s};' % (c, k, ', '.join('0x%06X' % v for v in tv)))
            cl.append('{0x%04X, pd_%s_c%d}' % (addr, c, k))
        out.append('static const PdCurve pd_%s_curve[] = {%s};' % (c, ', '.join(cl)))
        out.append('static const PdKnob pd_%s_k[] = {%s};' % (c, ', '.join(
            '{"%s", %d}' % (lab, round(d[lab] * 100)) for lab, _, _ in p['knobs'])))
        tl = []
        for t, tb in enumerate(knob_tables(name)):
            flat = [v for row in tb['val'] for v in row]
            total += 4 * len(flat)
            out.append('static const uint16_t pd_%s_t%d_a[] = {%s};' % (c, t, ', '.join('0x%04X' % a for a in tb['addr'])))
            out.append('static const uint32_t pd_%s_t%d_v[] = {%s};' % (c, t, ', '.join('0x%06X' % v for v in flat)))
            k2 = tb['knobs'] + [0] * (2 - len(tb['knobs']))
            s2 = tb['steps'] + [1] * (2 - len(tb['steps']))
            tl.append('{%d, {%d, %d}, {%d, %d}, %d, pd_%s_t%d_a, pd_%s_t%d_v}' % (
                len(tb['knobs']), k2[0], k2[1], s2[0], s2[1], len(tb['addr']), c, t, c, t))
        out.append('static const PdTab pd_%s_tab[] = {%s};' % (c, ', '.join(tl)))
        defs.append('  {"%s", 0x%06X, %d, 0x%04X, %d, pd_%s_init, %d, pd_%s_curve, %d, pd_%s_k, %d, pd_%s_tab},' % (
            name, p['colour'], FX_DIRT, R.PAR, R.NPAR, c, len(cl), c, len(p['knobs']), c, len(tl), c))
        total += 4 * (R.NPAR + 257 * len(cl))
        print('%-14s %d knobs, %d tables, %d curves' % (name, len(p['knobs']), len(tl), len(cl)))
    out.append('')
    out.append('static const PdDef PD_PEDALS[] = {')
    out += defs
    out.append('};')
    out.append('static const int PD_N = sizeof PD_PEDALS / sizeof PD_PEDALS[0];')
    out.append('')
    path = os.path.join(FW, 'pedals_dsp.h')
    tmp = path + '.tmp'
    open(tmp, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    os.replace(tmp, path)
    print('wrote %s (%d KB of tables)' % (path, total // 1024))


if __name__ == '__main__':
    emit(sys.argv[1:] or list(dm.PEDALS))
